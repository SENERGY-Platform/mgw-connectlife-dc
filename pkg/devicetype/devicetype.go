func displayName(a connectlife.Appliance) string {
	parts := []string{"ConnectLife"}
	typeName := a.DeviceTypeName
	if strings.TrimSpace(typeName) == "" {
		typeName = typeNames[a.DeviceTypeCode]
	}
	for _, p := range []string{typeName, a.DeviceFeatureName} {
		if p = strings.TrimSpace(p); p != "" {
			parts = append(parts, p)
		}
	}
	return strings.Join(parts, " ") + " (" + a.TypeKey() + ")"
}

// InferType maps a status value to a content type. The cloud sends numbers mostly as strings;
// every numeric value becomes Float, so a later fractional value still fits.
func InferType(v any) models.Type {
	switch value := v.(type) {
	case json.Number, float64, int, int64:
		return models.Float
	case string:
		if _, err := strconv.ParseFloat(value, 64); err == nil {
			return models.Float
		}
	}
	return models.String
}

// Writable returns the writable properties of a property list, nil if the list is empty.
func Writable(info []connectlife.PropertyInfo) map[string]bool {
	if len(info) == 0 {
		return nil
	}
	result := map[string]bool{}
	for _, p := range info {
		if p.Writable() {
			result[p.Key] = true
		}
	}
	return result
}

// PropertyTypes reads the property types from the status service of a device type.
func PropertyTypes(dt models.DeviceType) map[string]models.Type {
	result := map[string]models.Type{}
	for _, s := range dt.Services {
		if s.LocalId != StatusService {
			continue
		}
		for _, out := range s.Outputs {
			for _, sub := range out.ContentVariable.SubContentVariables {
				result[sub.Name] = sub.Type
			}
		}
	}
	return result
}

// StatusEvent converts a status list to the event payload of the status service.
// Properties unknown to the device type and values that do not fit its type are left out.
func StatusEvent(status map[string]any, types map[string]models.Type) map[string]any {
	result := map[string]any{}
	for name, value := range status {
		t, ok := types[name]
		if !ok {
			continue
		}
		switch t {
		case models.Float:
			if f, ok := toFloat(value); ok {
				result[name] = f
			}
		case models.String:
			result[name] = fmt.Sprint(value)
		}
	}
	return result
}

// MissingProperties lists properties of the status list that the device type does not know.
func MissingProperties(status map[string]any, types map[string]models.Type) []string {
	result := []string{}
	for name := range status {
		if _, ok := types[name]; !ok {
			result = append(result, name)
		}
	}
	sort.Strings(result)
	return result
}

func toFloat(v any) (float64, bool) {
	switch value := v.(type) {
	case json.Number:
		f, err := value.Float64()
		return f, err == nil
	case float64:
		return value, true
	case string:
		f, err := strconv.ParseFloat(value, 64)
		return f, err == nil
	}
	return 0, false
}
