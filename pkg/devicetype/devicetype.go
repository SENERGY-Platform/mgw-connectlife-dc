// Package devicetype derives a SENERGY device type from the property list of a ConnectLife
// appliance model, completed by the status list the appliance reports.
//
// ConnectLife property names differ between appliance models, also within one appliance
// class (tumble dryers use type codes 004, 030 and 032 with different property sets).
// A device type is therefore generated per type code and feature code, with one event
// service carrying all properties and one generic command service that writes a property.
package devicetype

import (
	"encoding/json"
	"errors"
	"fmt"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/SENERGY-Platform/mgw-connectlife-dc/pkg/connectlife"
	"github.com/SENERGY-Platform/models/go/models"
)

const (
	AttrType        = "connectlife/type"
	AttrTypeCode    = "connectlife/device_type_code"
	AttrFeatureCode = "connectlife/device_feature_code"

	StatusService      = "status"
	SetPropertyService = "set_property"

	statusVariable = "status"
)

// variableName is the rule of the device-repository for content variable names.
var variableName = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9-_]*$`)

type Protocol struct {
	Id        string
	SegmentId string
}

// Generate builds a device type without ids; the device-manager assigns them on creation.
//
// The properties are the union of the property list of the model (available while the appliance
// is offline) and its status list. A property with a reported value gets the type of that value;
// one known only from the property list is numeric, as all values in property lists are enumerations
// or numbers. Names the device-repository rejects are left out. Without any usable property
// the result is an error, because a device type created from it could never carry values.
func Generate(a connectlife.Appliance, info []connectlife.PropertyInfo, protocol Protocol) (models.DeviceType, error) {
	known := map[string]bool{}
	for _, p := range info {
		known[p.Key] = true
	}
	for name := range a.StatusList {
		known[name] = true
	}
	names := make([]string, 0, len(known))
	for name := range known {
		if variableName.MatchString(name) {
			names = append(names, name)
		}
	}
	if len(names) == 0 {
		return models.DeviceType{}, errors.New("neither property list nor status list has usable properties")
	}
	sort.Strings(names)
	properties := make([]models.ContentVariable, 0, len(names))
	for _, name := range names {
		t := models.Float
		if value, ok := a.StatusList[name]; ok {
			t = InferType(value)
		}
		properties = append(properties, annotate(models.ContentVariable{
			Name:      name,
			Type:      t,
			OmitEmpty: true,
		}))
	}

	setDescription := "Writes one property. Which properties accept writes depends on the appliance model."
	if writable := Writable(info); len(writable) > 0 {
		keys := make([]string, 0, len(writable))
		for k := range writable {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		setDescription = "Writes one property. Writable: " + strings.Join(keys, ", ") + "."
	}

	dt := models.DeviceType{
		Name:          displayName(a),
		DeviceClassId: deviceClasses[a.DeviceTypeCode],
		Description:   fmt.Sprintf("ConnectLife appliance, type code %s, feature code %s. Generated by mgw-connectlife-dc.", a.DeviceTypeCode, a.DeviceFeatureCode),
		Attributes: []models.Attribute{
			{Key: AttrType, Value: a.TypeKey()},
			{Key: AttrTypeCode, Value: a.DeviceTypeCode},
			{Key: AttrFeatureCode, Value: a.DeviceFeatureCode},
		},
		Services: []models.Service{
			{
				LocalId:     StatusService,
				Name:        "Status",
				Description: "All properties the ConnectLife cloud reports for the appliance.",
				Interaction: models.EVENT_AND_REQUEST,
				ProtocolId:  protocol.Id,
				Outputs: []models.Content{{
					ContentVariable: models.ContentVariable{
						Name:                statusVariable,
						Type:                models.Structure,
						SubContentVariables: properties,
					},
					Serialization:     models.JSON,
					ProtocolSegmentId: protocol.SegmentId,
				}},
			},
			{
				LocalId:     SetPropertyService,
				Name:        "Set Property",
				Description: setDescription,
				Interaction: models.REQUEST,
				ProtocolId:  protocol.Id,
				Inputs: []models.Content{{
					ContentVariable: models.ContentVariable{
						Name: "command",
						Type: models.Structure,
						SubContentVariables: []models.ContentVariable{
							{Name: "property", Type: models.String},
							{Name: "value", Type: models.String},
						},
					},
					Serialization:     models.JSON,
					ProtocolSegmentId: protocol.SegmentId,
				}},
			},
		},
	}
	dt.Services = append(dt.Services, actionCommands(info, protocol)...)
	return dt, nil
}

